          .text-h6 2. Соблюдение стандартов
          p Соблюдайте сценарии общения и внутренние регламенты компании. Четко следуйте инструкциям и фиксируйте обращения по правилам. Следите за качеством речи: без пауз, лишних слов и звуков. Проверяйте информацию перед тем, как озвучить её клиенту.
