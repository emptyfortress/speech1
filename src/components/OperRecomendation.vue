          p Сохраняйте спокойствие даже при сложных разговорах. Не переходите на эмоции и не спорьте с клиентом. Следуйте алгоритмам, но будьте гибкими, чтобы найти оптимальное решение. При необходимости привлекайте старшего специалиста, чтобы сохранить качество обслуживания.

        div(v-else-if="selection === 2")
          .text-h6 1. Профессионализм в общении
          p Начинайте разговор с приветствия и представления. Старайтесь поддерживать дружелюбный, но деловой тон. Избегайте жаргона и непроверенной информации. Уточняйте, если что-то неясно, и подводите итоги разговора. Фиксируйте обращения клиента точно и своевременно в системе.

          .text-h6 2. Управление временем и внимательность
          p Старайтесь решать обращения оперативно, без потери качества. Не отвлекайтесь во время разговора и сосредоточьтесь на клиенте. Используйте шаблоны и подсказки для ускорения работы, но адаптируйте их под конкретную ситуацию. Соблюдайте регламент и соблюдайте порядок звонков.

        div(v-else)
          .text-h6 1. Установление доверия
